const path = require('path');
const express = require('express');
const cookieParser = require('cookie-parser');
const db = require('./db');
const {
  createCascade,
  getCascade,
  listCascades,
  cancelCascade,
  holdCascade,
  resumeCascade,
  deleteCascade,
  cancelLevelOrder,
  editPendingLevel,
  editPlacedLevel,
  editSellPrice,
} = require('./cascadeEngine');
const gateClient = require('./gateClient');
const { normalizeSymbol } = require('./symbol');
const { encrypt, decrypt } = require('./secretsCrypto');
const {
  SESSION_COOKIE_NAME,
  verifyPassword,
  hashPassword,
  createSession,
  destroySession,
  invalidateUserSessions,
  peekPasswordSetToken,
  consumePasswordSetToken,
  inviteUser,
  createResetLinkForEmail,
  cookieOptions,
  requireAuth,
  requireAdmin,
  checkLoginRateLimit,
  recordFailedLogin,
  clearLoginRateLimit,
  loginPageHtml,
  setPasswordPageHtml,
  invalidLinkPageHtml,
} = require('./auth');

const REQUIRED_FIELDS = [
  'symbol',
  'base_price',
  'base_amount_usdt',
  'price_step_pct',
  'amount_step_pct',
  'num_levels',
  'take_profit_base_pct',
  'take_profit_step_pct',
];

function isForceDryRun() {
  return String(process.env.FORCE_DRY_RUN || 'false').toLowerCase() === 'true';
}

function buildClientForUser(user) {
  if (!user.gate_api_key_encrypted || !user.gate_api_secret_encrypted) return null;
  const apiKey = decrypt(user.gate_api_key_encrypted, `${user.id}:gate_api_key`);
  const apiSecret = decrypt(user.gate_api_secret_encrypted, `${user.id}:gate_api_secret`);
  return gateClient.createClient({ apiKey, apiSecret, dryRun: isForceDryRun() || !!user.dry_run });
}

function buildApp() {
  const app = express();
  app.use(express.json());
  app.use(express.urlencoded({ extended: false }));
  app.use(cookieParser());

  // --- Auth routes - must be registered before requireAuth below ---
  app.get('/login', (req, res) => {
    res.send(loginPageHtml());
  });

  app.post('/login', (req, res) => {
    const { email, password } = req.body || {};
    const rateLimit = checkLoginRateLimit(req.ip);
    if (!rateLimit.allowed) {
      return res.status(429).send(loginPageHtml('Too many attempts. Try again in a few minutes.'));
    }

    const user = db.prepare('SELECT * FROM users WHERE email = ?').get(email);
    if (!user || !verifyPassword(password || '', user.password_hash)) {
      recordFailedLogin(req.ip);
      return res.status(401).send(loginPageHtml('Invalid email or password.'));
    }

    clearLoginRateLimit(req.ip);
    const { token } = createSession(user.id);
    res.cookie(SESSION_COOKIE_NAME, token, cookieOptions());
    res.redirect('/');
  });

  app.post('/logout', (req, res) => {
    const token = req.cookies && req.cookies[SESSION_COOKIE_NAME];
    if (token) destroySession(token);
    res.clearCookie(SESSION_COOKIE_NAME, cookieOptions());
    res.redirect('/login');
  });

  // Serves both "invite - set your first password" and "forgot password" links -
  // same single-use token mechanism, generated by the create-invite.js /
  // create-reset-link.js CLI scripts and handed to the user manually.
  app.get('/set-password', (req, res) => {
    const userId = peekPasswordSetToken(req.query.token);
    if (!userId) return res.status(400).send(invalidLinkPageHtml());
    res.send(setPasswordPageHtml({ token: req.query.token, title: 'Set your password' }));
  });

  app.post('/set-password', (req, res) => {
    const { token, password, confirm_password: confirmPassword } = req.body || {};
    if (!peekPasswordSetToken(token)) {
      return res.status(400).send(invalidLinkPageHtml());
    }
    if (!password || password.length < 8) {
      return res
        .status(400)
        .send(setPasswordPageHtml({ token, title: 'Set your password', errorMessage: 'Password must be at least 8 characters.' }));
    }
    if (password !== confirmPassword) {
      return res
        .status(400)
        .send(setPasswordPageHtml({ token, title: 'Set your password', errorMessage: 'Passwords do not match.' }));
    }

    const userId = consumePasswordSetToken(token);
    if (!userId) return res.status(400).send(invalidLinkPageHtml());

    db.prepare('UPDATE users SET password_hash = ? WHERE id = ?').run(hashPassword(password), userId);
    invalidateUserSessions(userId); // any old sessions (e.g. from a compromised password) stop working

    const { token: sessionToken } = createSession(userId);
    res.cookie(SESSION_COOKIE_NAME, sessionToken, cookieOptions());
    res.redirect('/');
  });

  app.use(requireAuth);
  app.use(express.static(path.join(__dirname, '..', 'public')));

  app.get('/status', (req, res) => {
    res.json({
      email: req.user.email,
      dryRun: isForceDryRun() || !!req.user.dry_run,
      apiKeyConfigured: !!req.user.gate_api_key_encrypted,
      isAdmin: !!req.user.is_admin,
    });
  });

  let trendingCache = { at: 0, data: [] };
  const TRENDING_CACHE_MS = 30 * 1000;

  app.get('/admin/market/trending', requireAdmin, async (req, res) => {
    try {
      if (Date.now() - trendingCache.at > TRENDING_CACHE_MS) {
        const tickers = await gateClient.getAllTickers();
        const top = tickers
          .filter((t) => t.currency_pair && t.currency_pair.endsWith('_USDT'))
          .map((t) => ({
            symbol: t.currency_pair,
            last: parseFloat(t.last),
            changePct: parseFloat(t.change_percentage),
            quoteVolume: parseFloat(t.quote_volume) || 0,
          }))
          .sort((a, b) => b.quoteVolume - a.quoteVolume)
          .slice(0, 30);
        trendingCache = { at: Date.now(), data: top };
      }
      res.json(trendingCache.data);
    } catch (err) {
      res.status(502).json({ error: `Could not fetch market data: ${err.message}` });
    }
  });

  app.get('/admin/users', requireAdmin, (req, res) => {
    const users = db
      .prepare(
        `SELECT id, email, is_admin, dry_run, created_at,
                (gate_api_key_encrypted IS NOT NULL) AS api_key_configured
         FROM users ORDER BY created_at ASC`
      )
      .all()
      .map((u) => ({
        id: u.id,
        email: u.email,
        isAdmin: !!u.is_admin,
        dryRun: !!u.dry_run,
        apiKeyConfigured: !!u.api_key_configured,
        createdAt: u.created_at,
      }));
    res.json(users);
  });

  function baseUrl() {
    return process.env.APP_BASE_URL || 'http://localhost:3000';
  }

  app.post('/admin/invite', requireAdmin, (req, res) => {
    const email = (req.body?.email || '').trim();
    if (!email) return res.status(400).json({ error: 'Email is required' });
    try {
      const { token } = inviteUser(email, { isAdmin: !!req.body?.isAdmin });
      res.status(201).json({ email, link: `${baseUrl()}/set-password?token=${token}`, expiresIn: '7 days' });
    } catch (err) {
      res.status(400).json({ error: err.message });
    }
  });

  app.post('/admin/reset-link', requireAdmin, (req, res) => {
    const email = (req.body?.email || '').trim();
    if (!email) return res.status(400).json({ error: 'Email is required' });
    try {
      const { token } = createResetLinkForEmail(email);
      res.status(201).json({ email, link: `${baseUrl()}/set-password?token=${token}`, expiresIn: '1 hour' });
    } catch (err) {
      res.status(400).json({ error: err.message });
    }
  });

  app.get('/settings', (req, res) => {
    res.json({
      email: req.user.email,
      apiKeyConfigured: !!req.user.gate_api_key_encrypted,
      gateApiKeyLast4: req.user.gate_api_key_last4 || null,
      dryRun: !!req.user.dry_run,
    });
  });

  app.post('/settings', (req, res) => {
    const { gate_api_key, gate_api_secret, dry_run } = req.body || {};
    const updates = {};

    if (gate_api_key || gate_api_secret) {
      if (!gate_api_key || !gate_api_secret) {
        return res.status(400).json({ error: 'Provide both API key and secret together' });
      }
      updates.gate_api_key_encrypted = encrypt(gate_api_key, `${req.user.id}:gate_api_key`);
      updates.gate_api_secret_encrypted = encrypt(gate_api_secret, `${req.user.id}:gate_api_secret`);
      updates.gate_api_key_last4 = gate_api_key.slice(-4);
    }
    if (dry_run !== undefined) {
      updates.dry_run = dry_run ? 1 : 0;
    }
    if (Object.keys(updates).length === 0) {
      return res.status(400).json({ error: 'Nothing to update' });
    }

    const sets = Object.keys(updates).map((k) => `${k} = @${k}`).join(', ');
    db.prepare(`UPDATE users SET ${sets} WHERE id = @id`).run({ ...updates, id: req.user.id });
    res.json({ ok: true });
  });

  app.post('/cascades', (req, res) => {
    const body = req.body || {};
    const missing = REQUIRED_FIELDS.filter((f) => body[f] === undefined || body[f] === null);
    if (missing.length > 0) {
      return res.status(400).json({ error: `Missing required fields: ${missing.join(', ')}` });
    }

    try {
      const id = createCascade(req.user.id, {
        symbol: normalizeSymbol(body.symbol),
        trigger_price: body.trigger_price ?? null,
        base_price: Number(body.base_price),
        base_amount_usdt: Number(body.base_amount_usdt),
        price_step_pct: Number(body.price_step_pct),
        amount_step_pct: Number(body.amount_step_pct),
        num_levels: Number(body.num_levels),
        take_profit_base_pct: Number(body.take_profit_base_pct),
        take_profit_step_pct: Number(body.take_profit_step_pct),
        poll_interval_seconds: body.poll_interval_seconds ? Number(body.poll_interval_seconds) : 60,
      });
      res.status(201).json(getCascade(req.user.id, id));
    } catch (err) {
      res.status(400).json({ error: err.message });
    }
  });

  app.get('/cascades', (req, res) => {
    res.json(listCascades(req.user.id));
  });

  app.get('/cascades/:id', (req, res) => {
    const cascade = getCascade(req.user.id, req.params.id);
    if (!cascade) return res.status(404).json({ error: 'Not found' });
    res.json(cascade);
  });

  app.post('/cascades/:id/cancel', async (req, res) => {
    const client = buildClientForUser(req.user);
    if (!client) return res.status(400).json({ error: 'Configure your Gate.io API key in Settings first' });
    const ok = await cancelCascade(req.user.id, req.params.id, client);
    if (!ok) return res.status(404).json({ error: 'Not found' });
    res.json(getCascade(req.user.id, req.params.id));
  });

  app.post('/cascades/:id/hold', (req, res) => {
    const ok = holdCascade(req.user.id, req.params.id);
    if (!ok) return res.status(400).json({ error: 'Cannot hold this cascade (not found, or not active/pending)' });
    res.json(getCascade(req.user.id, req.params.id));
  });

  app.post('/cascades/:id/resume', (req, res) => {
    const ok = resumeCascade(req.user.id, req.params.id);
    if (!ok) return res.status(400).json({ error: 'Cannot resume this cascade (not found, or not held)' });
    res.json(getCascade(req.user.id, req.params.id));
  });

  app.delete('/cascades/:id', async (req, res) => {
    const client = buildClientForUser(req.user);
    if (!client) return res.status(400).json({ error: 'Configure your Gate.io API key in Settings first' });
    const ok = await deleteCascade(req.user.id, req.params.id, client);
    if (!ok) return res.status(404).json({ error: 'Not found' });
    res.json({ deleted: true });
  });

  app.post('/cascades/:id/levels/:levelId/cancel', async (req, res) => {
    const client = buildClientForUser(req.user);
    if (!client) return res.status(400).json({ error: 'Configure your Gate.io API key in Settings first' });
    try {
      const result = await cancelLevelOrder(req.user.id, req.params.id, req.params.levelId, req.body?.side, client);
      if (!result.ok) return res.status(400).json({ error: result.error });
      res.json(getCascade(req.user.id, req.params.id));
    } catch (err) {
      res.status(400).json({ error: err.message });
    }
  });

  app.patch('/cascades/:id/levels/:levelId', async (req, res) => {
    const cascade = getCascade(req.user.id, req.params.id);
    if (!cascade) return res.status(404).json({ error: 'Not found' });
    const level = cascade.levels.find((l) => l.id === req.params.levelId);
    if (!level) return res.status(404).json({ error: 'Level not found' });

    const body = req.body || {};
    try {
      let result;
      if (body.sell_target_price !== undefined) {
        const client = buildClientForUser(req.user);
        if (!client) return res.status(400).json({ error: 'Configure your Gate.io API key in Settings first' });
        result = await editSellPrice(
          req.user.id,
          req.params.id,
          req.params.levelId,
          { sell_target_price: Number(body.sell_target_price) },
          client
        );
      } else if (level.status === 'pending') {
        result = editPendingLevel(req.user.id, req.params.id, req.params.levelId, {
          target_price: Number(body.target_price),
          amount_usdt: Number(body.amount_usdt),
          take_profit_pct: Number(body.take_profit_pct ?? level.take_profit_pct),
        });
      } else if (level.status === 'placed') {
        const client = buildClientForUser(req.user);
        if (!client) return res.status(400).json({ error: 'Configure your Gate.io API key in Settings first' });
        result = await editPlacedLevel(
          req.user.id,
          req.params.id,
          req.params.levelId,
          { target_price: Number(body.target_price), amount_usdt: Number(body.amount_usdt) },
          client
        );
      } else {
        return res.status(400).json({ error: 'This level cannot be edited right now' });
      }

      if (!result.ok) return res.status(400).json({ error: result.error });
      res.json(getCascade(req.user.id, req.params.id));
    } catch (err) {
      res.status(400).json({ error: err.message });
    }
  });

  return app;
}

module.exports = { buildApp };
